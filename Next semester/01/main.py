import tkinter as tk  # 匯入 tkinter 模組，並將它縮寫為 tk，這是用來建立圖形介面 (GUI) 的套件

# ==========================================
# 1. 取得使用者輸入
# ==========================================
# 使用 input() 提示使用者輸入文字，並將輸入的文字透過 int() 轉換為整數
n = int(input("請輸入非負整數 N："))

# ==========================================
# 2. 計算帕斯卡三角形的數字
# ==========================================
rows = []  # 建立一個空的串列 (List)，用來儲存所有層的數字

# 使用 for 迴圈，從 0 執行到 n (包含 n)
for i in range(n + 1):
    row = []  # 建立一個空的串列，用來儲存「目前這一層」的數字
    
    # 再使用一個迴圈，決定這一層要有幾個數字 (第 i 層會有 i+1 個數字)
    for j in range(i + 1):
        # 判斷：如果是每一列的最左邊 (j==0) 或是最右邊 (j==i)，數字固定是 1
        if j == 0 or j == i:
            row.append(1)  # 將 1 加入到目前的層中
        # 如果是中間的數字，則等於上一層相鄰兩個數字相加
        else:
            # 上一列是 rows[i - 1]
            # 相鄰的兩個數字分別是 j-1 與 j 索引位置的數字
            row.append(rows[i - 1][j - 1] + rows[i - 1][j])
            
    # 將計算好的這一層串列，加入到整體的 rows 串列中
    rows.append(row)

# ==========================================
# 3. 建立圖形介面 (GUI)
# ==========================================
window = tk.Tk()                # 建立一個主視窗
window.title("帕斯卡三角形")    # 設定視窗的標題名稱
window.geometry("800x600")      # 設定視窗的初始大小，寬 800 像素，高 600 像素

# ==========================================
# 4. 把數字畫到視窗畫面上
# ==========================================
# 取出 rows 串列裡面的每一層
for row in rows:
    # 針對每一層，建立一個 Frame (框架)，方便我們把這一層的數字水平排列在一起
    row_frame = tk.Frame(window)
    # pack() 是用來放置元件的方法，pady=2 表示上下留白 2 像素
    row_frame.pack(pady=2)

    # 取出這一層裡面的每一個數字
    for value in row:
        # 建立一個 Label (標籤) 用來顯示文字
        lbl = tk.Label(
            row_frame,           # 這個標籤要放在剛剛建立的 row_frame 裡面
            text=str(value),     # 將數字轉換成字串文字來顯示
            font=("Arial", 14),  # 設定字體為 Arial，大小為 14
            width=4              # 設定固定寬度，讓數字排列起來比較整齊
        )
        # 把這個標籤放到畫面上，side="left" 表示從左邊開始排，padx=2 表示左右留白 2 像素
        lbl.pack(side="left", padx=2)

# ==========================================
# 5. 啟動程式
# ==========================================
# 呼叫 mainloop() 讓視窗持續顯示，並等待使用者操作 (例如點擊關閉按鈕)
window.mainloop()
